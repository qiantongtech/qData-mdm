import request from '@/utils/request'

// 来源详情页：查询全部有效来源记录，并返回当前主数据版本的有效字段取值来源。
export function getSourceDetail(instanceId, masterDataId) {
  return request({
    url: `/master/source/rel/records/${instanceId}/${masterDataId}`,
    method: 'get'
  })
}
