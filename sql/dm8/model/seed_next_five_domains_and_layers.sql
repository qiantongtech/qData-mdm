SELECT '主数据域' AS OBJECT_TYPE, s.CODE AS OBJECT_CODE, '主数据域缺失、重复、停用或已删除' AS RESULT
FROM expected_project s
LEFT JOIN "QDATA_MDM"."MODEL_PROJECT" d ON d.CODE = s.CODE
GROUP BY s.CODE
HAVING COUNT(d.ID) <> 1 OR MAX(CASE WHEN d.DEL_FLAG = '0' AND d.VALID_FLAG = '1' THEN 1 ELSE 0 END) <> 1
UNION ALL
SELECT '模型目录', s.CODE, '目录缺失、重复、停用或归属不符。预期域 / 父目录为 ' || s.PROJECT_CODE || ' / ' || s.PARENT_CODE
FROM expected_layer s
LEFT JOIN "QDATA_MDM"."MODEL_LAYER" l ON l.CODE = s.CODE
LEFT JOIN "QDATA_MDM"."MODEL_PROJECT" d ON d.ID = l.PROJECT_ID AND d.CODE = s.PROJECT_CODE
    AND d.DEL_FLAG = '0' AND d.VALID_FLAG = '1'
LEFT JOIN "QDATA_MDM"."MODEL_LAYER" p ON p.ID = l.PARENT_ID AND p.PROJECT_ID = d.ID AND p.CODE = s.PARENT_CODE
    AND p.DEL_FLAG = '0' AND p.VALID_FLAG = '1'
GROUP BY s.PROJECT_CODE, s.CODE, s.PARENT_CODE
HAVING COUNT(l.ID) <> 1
    OR MAX(CASE WHEN l.DEL_FLAG = '0' AND l.VALID_FLAG = '1' AND d.ID IS NOT NULL
                 AND ((s.PARENT_CODE = '-' AND l.PARENT_ID = 0)
                      OR (s.PARENT_CODE <> '-' AND p.ID IS NOT NULL))
                THEN 1 ELSE 0 END) <> 1
