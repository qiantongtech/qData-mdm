WITH pending_change AS (
    SELECT old_row.ID AS LEGACY_ID, seed.CODE,
           DATEADD(SECOND, seed.SLOT * 240, TIMESTAMP '2026-11-13 08:30:00') AS CREATED_AT,
           DATEADD(SECOND, seed.SLOT * 240 + 120, TIMESTAMP '2026-11-13 08:30:00') AS UPDATED_AT,
           CASE WHEN old_row.CREATE_TIME = old_row.UPDATE_TIME AND old_row.DESCRIPTION = seed.DESCRIPTION
                     AND old_row.CREATE_BY = '吴同' AND old_row.CREATOR_ID = 2
                     AND old_row.UPDATE_BY = '吴同' AND old_row.UPDATER_ID = 2 THEN 1 ELSE 0 END AS RETIME
    FROM (
        SELECT 'PRODUCT' AS CODE, 'PRD' AS LEGACY_CODE, '产品主数据' AS NAME, 0 AS SLOT, '成品分类、产品型号、版本和商业属性的统一管理。' AS DESCRIPTION FROM DUAL
        UNION ALL SELECT 'EQUIPMENT_ASSET', 'AST', '设备资产主数据', 11, '生产设备、公用设施及固定资产标识的统一管理。' FROM DUAL
        UNION ALL SELECT 'FINANCIAL_REFERENCE', 'FIN', '财务基础主数据', 22, '会计科目、责任核算单元和资金账户等财务基础信息。' FROM DUAL
        UNION ALL SELECT 'PROJECT', 'PRJ', '项目主数据', 33, '研发、工程、改造项目及相关团队资源的统一管理。' FROM DUAL
        UNION ALL SELECT 'LOCATION_FACILITY', 'LOC', '地点与设施主数据', 44, '行政地域、经营场所、建筑空间和仓储库位的统一管理。' FROM DUAL
    ) seed
    JOIN "QDATA_MDM"."MODEL_PROJECT" old_row ON old_row.CODE = seed.LEGACY_CODE
    WHERE NOT EXISTS (SELECT 1 FROM "QDATA_MDM"."MODEL_PROJECT" x WHERE x.CODE = seed.CODE)
      AND old_row.NAME = seed.NAME AND old_row.DEL_FLAG = '0' AND old_row.VALID_FLAG = '1'
      AND NOT EXISTS (SELECT 1 FROM "QDATA_MDM"."MODEL_PROJECT" x WHERE x.CODE = old_row.CODE AND x.ID <> old_row.ID)
)
UPDATE "QDATA_MDM"."MODEL_PROJECT" t
SET (CODE, CREATE_TIME, UPDATE_TIME) = (
    SELECT s.CODE,
           CASE WHEN s.RETIME = 1 THEN s.CREATED_AT ELSE t.CREATE_TIME END,
           CASE WHEN s.RETIME = 1 THEN s.UPDATED_AT ELSE t.UPDATE_TIME END
    FROM pending_change s
    WHERE s.LEGACY_ID = t.ID
)
WHERE t.ID IN (SELECT s.LEGACY_ID FROM pending_change s);

