-- 从 2026-11-13 08:30:00 起按清单的树形顺序录入。SLOT 从 0 开始，每条记录创建时间间隔 4 分钟。
-- 修改时间比本条创建时间晚 2 分钟。
-- 已有业务编码跳过。旧编码仅在同名、唯一、启用且归属匹配时原位换码，保留 ID。
