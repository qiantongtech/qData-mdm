            AND i.SORT_ORDER = 2 AND i.TYPE = 'SERIAL_NUMBER' AND i.SEQUENCE_LENGTH = 8
            AND i.SEQUENCE_START = 1 AND i.STEP_SIZE = 1
            AND TRIM(i.PAD_CHAR) IN ('LEFT_ZERO', '0') AND TRIM(i.RESET_METHOD) = 'NONE'
      )
) THEN '已生效，' || s.PREFIX_TEXT || ' 加 8 位流水'
     ELSE '生效版本或规则与约定不符，预期 ' || s.PREFIX_TEXT || ' 加 8 位流水'
END
FROM expected_scheme s
UNION ALL
SELECT '主数据模型', s.CODE, CASE
    WHEN m.ID IS NULL THEN '模型缺失，请检查目录 ' || s.LAYER_CODE
    WHEN dp.ID IS NULL OR dl.ID IS NULL OR m.TYPE <> 'NORMAL' OR m.PARENT_ID IS NOT NULL
      OR (s.PARENT_LAYER_CODE = '-' AND COALESCE(dl.PARENT_ID, -1) <> 0)
      OR (s.PARENT_LAYER_CODE <> '-' AND parent_layer.ID IS NULL)
        THEN '模型归属不符，预期 ' || s.PROJECT_CODE || ' / ' || s.LAYER_CODE
    WHEN m.PUBLISHED_INSTANCE_ID IS NOT NULL THEN '存在发布实例，请核对发布状态'
    WHEN mv.ID IS NULL THEN '缺少可用的当前版本'
    WHEN mv.VERSION_NO <> 'V1.0' OR COALESCE(mv.STATUS, -1) <> 0 OR mv.BASE_VERSION_ID IS NOT NULL
        THEN '当前版本不符合 V1.0 初始草稿要求，状态码 ' || COALESCE(CAST(mv.STATUS AS VARCHAR(16)), '空')
    WHEN COALESCE(field_total.ACTUAL_COUNT, 0) < s.FIELD_COUNT
        THEN '草稿字段未齐 ' || CAST(COALESCE(field_total.ACTUAL_COUNT, 0) AS VARCHAR(16))
             || '/' || CAST(s.FIELD_COUNT AS VARCHAR(16))
             || '，请核对已删除字段或关联模型'
    ELSE '已确认为草稿 ' || mv.VERSION_NO || '，字段 ' || CAST(field_total.ACTUAL_COUNT AS VARCHAR(16))
         || '/' || CAST(s.FIELD_COUNT AS VARCHAR(16)) || '，归属 ' || dp.NAME || ' / '
         || CASE WHEN parent_layer.ID IS NOT NULL THEN parent_layer.NAME || ' / ' ELSE '' END || dl.NAME
END
