LEFT JOIN MODEL_BASE m ON m.CODE = s.MODEL_CODE AND m.DEL_FLAG = 0
LEFT JOIN MODEL_COLUMN f ON f.MODEL_ID = m.ID AND f.CODE = s.FIELD_CODE AND f.DEL_FLAG = 0
LEFT JOIN MODEL_DICT_TYPE d ON d.ID = f.DICT_TYPE_ID
LEFT JOIN MODEL_ENCODING_VERSION v ON v.ID = f.ENCODING_VERSION_ID
LEFT JOIN MODEL_ENCODING e ON e.ID = v.ENCODING_ID
UNION ALL
SELECT CASE WHEN s.PARENT_CODE = '-' THEN '分类模型' ELSE '子模型' END, s.CODE,
       CASE
           WHEN m.ID IS NULL THEN '模型缺失，请检查目录或所属主模型的草稿状态'
           WHEN p.ID IS NULL OR l.ID IS NULL OR COALESCE(m.TYPE, '-') <> s.MODEL_TYPE
             OR (s.PARENT_CODE <> '-' AND parent.ID IS NULL)
             OR (s.PARENT_CODE = '-' AND m.PARENT_ID IS NOT NULL)
               THEN '归属不符，预期 ' || s.PROJECT_CODE || ' / ' || s.LAYER_CODE || '，父模型 ' || s.PARENT_CODE
           WHEN m.PUBLISHED_INSTANCE_ID IS NOT NULL OR (s.PARENT_CODE <> '-' AND m.VERSION_ID IS NOT NULL)
             OR v.ID IS NULL OR v.STATUS <> 0 OR v.VERSION_NO <> 'V1.0' OR v.BASE_VERSION_ID IS NOT NULL
               THEN '请核对模型或所属主模型的 V1.0 草稿状态'
           WHEN (SELECT COUNT(*) FROM MODEL_COLUMN c WHERE c.MODEL_ID = m.ID AND c.DEL_FLAG = 0) < s.FIELD_COUNT
               THEN '字段未齐，预期至少 ' || CAST(s.FIELD_COUNT AS VARCHAR(16)) || ' 个字段'
           ELSE '已初始化 ' || p.NAME || ' / ' || l.NAME
                || CASE WHEN parent.ID IS NOT NULL THEN ' / ' || parent.NAME ELSE '' END
       END
FROM expected_extension s
LEFT JOIN MODEL_BASE m ON m.CODE = s.CODE AND m.DEL_FLAG = 0
LEFT JOIN MODEL_PROJECT p ON p.CODE = s.PROJECT_CODE AND p.ID = m.PROJECT_ID AND p.DEL_FLAG = 0
LEFT JOIN MODEL_LAYER l ON l.CODE = s.LAYER_CODE AND l.ID = m.LAYER_ID AND l.PROJECT_ID = p.ID
    AND l.PARENT_ID = 0 AND l.DEL_FLAG = 0
LEFT JOIN MODEL_BASE parent ON parent.ID = m.PARENT_ID AND parent.CODE = s.PARENT_CODE
    AND parent.PROJECT_ID = p.ID AND parent.LAYER_ID = l.ID AND parent.DEL_FLAG = 0
    AND parent.PARENT_ID IS NULL AND parent.PUBLISHED_INSTANCE_ID IS NULL
LEFT JOIN MODEL_VERSION v ON v.ID = CASE WHEN s.PARENT_CODE = '-' THEN m.VERSION_ID ELSE parent.VERSION_ID END
    AND v.MODEL_ID = CASE WHEN s.PARENT_CODE = '-' THEN m.ID ELSE parent.ID END AND v.DEL_FLAG = 0
UNION ALL
SELECT CASE WHEN s.FIELD_CATEGORY = 'CLASS' THEN '分类字段' ELSE '子模型关联字段' END,
       s.MODEL_CODE || '.' || s.FIELD_CODE,
       CASE
           WHEN c.ID IS NULL THEN '字段缺失，预期关联 ' || s.TARGET_CODE
           WHEN r.ID IS NOT NULL AND c.COLUMN_CATEGORY = s.FIELD_CATEGORY AND c.RELATED_CODE = s.KEY_CODE
             AND c.DISPLAY_CODE = s.DISPLAY_CODE AND COALESCE(c.NODE_RULE, '-') = s.NODE_RULE
             AND COALESCE(c.DISPLAY_MODE, '-') = s.DISPLAY_MODE
               THEN '已关联 ' || r.NAME || '，键 ' || s.KEY_CODE || '，展示 ' || s.DISPLAY_CODE
           ELSE '现有字段配置需核对，预期关联 ' || s.TARGET_CODE
       END
FROM expected_extension_link s
LEFT JOIN MODEL_BASE m ON m.CODE = s.MODEL_CODE AND m.DEL_FLAG = 0
LEFT JOIN MODEL_COLUMN c ON c.MODEL_ID = m.ID AND c.CODE = s.FIELD_CODE AND c.DEL_FLAG = 0
LEFT JOIN MODEL_BASE r ON r.ID = c.RELATED_MODEL_ID AND r.CODE = s.TARGET_CODE AND r.DEL_FLAG = 0
    AND r.TYPE = CASE WHEN s.FIELD_CATEGORY = 'CLASS' THEN 'CATEGORY' ELSE 'NORMAL' END
