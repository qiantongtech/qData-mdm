-- 3.1 先写入分类模型及其 V1.0 草稿。
MERGE INTO MODEL_BASE m
USING (
    SELECT s.CODE, s.NAME, s.MODEL_TYPE, s.DESCRIPTION, s.OLD_DESCRIPTION, s.ENTERED_AT,
           MIN(d.ID) AS PROJECT_ID, MIN(l.ID) AS LAYER_ID, CAST(NULL AS BIGINT) AS PARENT_ID
    FROM (
        SELECT 'CUS_INDUSTRY_TREE' AS CODE, '客户行业分类' AS NAME, 'CATEGORY' AS MODEL_TYPE, 'CUSTOMER' AS PROJECT_CODE, 'CUS_SEGMENTS' AS LAYER_CODE, '-' AS PARENT_LAYER_CODE, '-' AS PARENT_CODE, '客户所属行业及细分行业的分类树' AS OLD_DESCRIPTION, '按客户实际经营活动维护行业及细分行业的层级，例如制造业下的装备制造和汽车零部件。客户档案引用末级行业，用于分派行业销售团队和统计客户结构。' AS DESCRIPTION, TIMESTAMP '2026-11-12 11:43:34.352741' AS ENTERED_AT FROM DUAL
        UNION ALL SELECT 'SUP_CATEGORY_TREE', '供应商供货品类', 'CATEGORY', 'SUPPLIER', 'SUP_PARTIES', '-', '-', '按供应能力维护可采购品类的分类树', '按照采购可寻源的供货能力维护品类树，区分金属原料、工业标准件和电气部件等。供应商档案记录主要供货品类，物料供货来源明细记录对应供货的具体品类。', TIMESTAMP '2026-11-12 11:44:51.352741' FROM DUAL
        UNION ALL SELECT 'MAT_CATEGORY_TREE', '物料分类树', 'CATEGORY', 'MATERIAL', 'MAT_ITEMS', '-', '-', '按物料用途和形态维护物料分类树', '按物料用途和形态维护原材料、外购件、自制件及包装材料的层级。物料档案引用末级节点，用于分类查找、采购归口和库存统计。', TIMESTAMP '2026-11-12 11:46:23.352741' FROM DUAL
    ) s
    JOIN MODEL_PROJECT d ON d.CODE = s.PROJECT_CODE AND d.DEL_FLAG = 0 AND COALESCE(d.VALID_FLAG, 1) = 1
    JOIN MODEL_LAYER l ON l.CODE = s.LAYER_CODE AND l.PROJECT_ID = d.ID
        AND l.DEL_FLAG = 0 AND COALESCE(l.VALID_FLAG, 1) = 1
    LEFT JOIN MODEL_LAYER lp ON lp.ID = l.PARENT_ID AND lp.CODE = s.PARENT_LAYER_CODE
        AND lp.PROJECT_ID = d.ID AND lp.PARENT_ID = 0 AND lp.DEL_FLAG = 0 AND COALESCE(lp.VALID_FLAG, 1) = 1
    WHERE (s.PARENT_LAYER_CODE = '-' AND l.PARENT_ID = 0) OR lp.ID IS NOT NULL
    GROUP BY s.CODE, s.NAME, s.MODEL_TYPE, s.DESCRIPTION, s.OLD_DESCRIPTION, s.ENTERED_AT
    HAVING COUNT(*) = 1
    ORDER BY s.ENTERED_AT
) s ON (m.CODE = s.CODE)
WHEN MATCHED THEN UPDATE SET
    m.PROJECT_ID = s.PROJECT_ID, m.LAYER_ID = s.LAYER_ID,
    m.DESCRIPTION = CASE WHEN m.DESCRIPTION IS NULL OR m.DESCRIPTION = s.OLD_DESCRIPTION
                         THEN s.DESCRIPTION ELSE m.DESCRIPTION END,
    m.CREATE_TIME = s.ENTERED_AT,
    m.UPDATE_TIME = CASE WHEN m.UPDATE_TIME IS NULL OR m.UPDATE_TIME = m.CREATE_TIME
                             OR m.UPDATE_TIME < s.ENTERED_AT THEN s.ENTERED_AT ELSE m.UPDATE_TIME END
WHERE m.TYPE = s.MODEL_TYPE AND m.DEL_FLAG = 0 AND m.PUBLISHED_INSTANCE_ID IS NULL
  AND m.PARENT_ID IS NULL
  AND (m.VERSION_ID IS NULL OR EXISTS (
      SELECT 1 FROM MODEL_VERSION v WHERE v.ID = m.VERSION_ID AND v.MODEL_ID = m.ID AND v.VERSION_NO = 'V1.0'
        AND v.STATUS = 0 AND v.DEL_FLAG = 0 AND v.BASE_VERSION_ID IS NULL
  ))
  AND NOT EXISTS (
      SELECT 1 FROM MODEL_VERSION v WHERE v.MODEL_ID = m.ID AND v.DEL_FLAG = 0
        AND (v.VERSION_NO <> 'V1.0' OR COALESCE(v.STATUS, -1) <> 0 OR v.BASE_VERSION_ID IS NOT NULL)
  )
  AND (m.CREATE_BY = 'mdm_first_five' OR INSTR(m.REMARK, '[MDM-SEED-FIRST-FIVE]') > 0
       OR (m.CREATE_BY = '吴同' AND m.CREATOR_ID = 2
