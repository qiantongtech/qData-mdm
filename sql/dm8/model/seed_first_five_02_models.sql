LEFT JOIN MODEL_BASE m ON m.CODE = s.CODE AND m.DEL_FLAG = 0
LEFT JOIN MODEL_PROJECT dp ON dp.CODE = s.PROJECT_CODE AND dp.ID = m.PROJECT_ID
    AND dp.DEL_FLAG = 0 AND COALESCE(dp.VALID_FLAG, 1) = 1
LEFT JOIN MODEL_LAYER dl ON dl.CODE = s.LAYER_CODE AND dl.ID = m.LAYER_ID AND dl.PROJECT_ID = dp.ID
    AND dl.DEL_FLAG = 0 AND COALESCE(dl.VALID_FLAG, 1) = 1
LEFT JOIN MODEL_LAYER parent_layer ON parent_layer.ID = dl.PARENT_ID AND parent_layer.CODE = s.PARENT_LAYER_CODE
    AND parent_layer.PROJECT_ID = dp.ID AND parent_layer.PARENT_ID = 0 AND parent_layer.DEL_FLAG = 0
    AND COALESCE(parent_layer.VALID_FLAG, 1) = 1
LEFT JOIN MODEL_VERSION mv ON mv.ID = m.VERSION_ID AND mv.MODEL_ID = m.ID AND mv.DEL_FLAG = 0
LEFT JOIN (
    SELECT MODEL_ID, COUNT(*) AS ACTUAL_COUNT FROM MODEL_COLUMN WHERE DEL_FLAG = 0 GROUP BY MODEL_ID
) field_total ON field_total.MODEL_ID = m.ID
UNION ALL
SELECT CASE WHEN s.DICT_CODE <> '-' THEN '字段参考数据' ELSE '字段编码方案' END,
       s.MODEL_CODE || '.' || s.FIELD_CODE,
       CASE
           WHEN m.ID IS NULL OR f.ID IS NULL THEN '模型或字段缺失'
           WHEN s.DICT_CODE <> '-' AND d.CODE = s.DICT_CODE
                AND d.DEL_FLAG = 0 AND COALESCE(d.VALID_FLAG, 1) = 1
               THEN '已关联 ' || d.CODE
           WHEN s.SCHEME_CODE <> '-' AND e.CODE = s.SCHEME_CODE AND f.ENCODING_MODE = 'AUTOMATIC'
                AND e.DEL_FLAG = 0 AND COALESCE(e.VALID_FLAG, 1) = 1 AND v.STATUS = 3 AND v.DEL_FLAG = 0
                AND COALESCE(v.VALID_FLAG, 1) = 1 AND (v.EFFECTIVE_TIME IS NULL OR v.EFFECTIVE_TIME <= CURRENT_TIMESTAMP)
               THEN '已关联 ' || e.CODE || ' ' || v.VERSION_NO
           WHEN m.PUBLISHED_INSTANCE_ID IS NOT NULL THEN '请通过模型修订绑定 ' ||
                CASE WHEN s.DICT_CODE <> '-' THEN s.DICT_CODE ELSE s.SCHEME_CODE END
           WHEN f.DICT_TYPE_ID IS NOT NULL OR f.ENCODING_VERSION_ID IS NOT NULL THEN '现有绑定需核对，预期 ' ||
                CASE WHEN s.DICT_CODE <> '-' THEN s.DICT_CODE ELSE s.SCHEME_CODE END
           ELSE '未绑定，预期 ' || CASE WHEN s.DICT_CODE <> '-' THEN s.DICT_CODE ELSE s.SCHEME_CODE END
       END
