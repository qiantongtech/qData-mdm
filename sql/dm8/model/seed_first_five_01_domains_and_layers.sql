SELECT '模型目录', s.CODE, '目录缺失、停用或归属不符，预期域和父目录为 ' || s.PROJECT_CODE || ' / ' || s.PARENT_CODE
FROM expected_layer s
LEFT JOIN MODEL_PROJECT d ON d.CODE = s.PROJECT_CODE AND d.DEL_FLAG = 0 AND COALESCE(d.VALID_FLAG, 1) = 1
LEFT JOIN MODEL_LAYER l ON l.CODE = s.CODE AND l.PROJECT_ID = d.ID AND l.DEL_FLAG = 0 AND COALESCE(l.VALID_FLAG, 1) = 1
LEFT JOIN MODEL_LAYER p ON p.ID = l.PARENT_ID AND p.PROJECT_ID = d.ID AND p.CODE = s.PARENT_CODE
    AND p.DEL_FLAG = 0 AND COALESCE(p.VALID_FLAG, 1) = 1
WHERE l.ID IS NULL OR (s.PARENT_CODE = '-' AND l.PARENT_ID <> 0) OR (s.PARENT_CODE <> '-' AND p.ID IS NULL)
