-- 3. 回填本批演示元数据的录入时间。各表按主键排序，日期和间隔模拟分批录入。
-- 只处理本批记录。修改时间仅在初始化时未单独修改的记录上同步。

MERGE INTO MODEL_PROJECT t
USING (
    SELECT r.ID, DATEADD(SECOND,
               (r.ENTRY_NO - 1) * 113 + MOD(r.ENTRY_NO * r.ENTRY_NO * 17, 29),
               TIMESTAMP '2026-11-12 08:12:17.352741') AS ENTERED_AT
    FROM (
        SELECT ID, ROW_NUMBER() OVER (ORDER BY ID) AS ENTRY_NO
        FROM MODEL_PROJECT
        WHERE (CREATE_BY = 'mdm_first_five' OR INSTR(REMARK, '[MDM-SEED-FIRST-FIVE]') > 0
            OR (CREATE_BY = '吴同' AND CREATOR_ID = 2
                AND (CREATE_TIME = TIMESTAMP '2026-11-12 08:00:00'
            OR TO_CHAR(CREATE_TIME, 'YYYY-MM-DD FF6') = '2026-11-12 352741')))
    ) r
) s ON (t.ID = s.ID)
WHEN MATCHED THEN UPDATE SET
    t.CREATE_TIME = s.ENTERED_AT,
    t.UPDATE_TIME = CASE
        WHEN t.UPDATE_TIME IS NULL
          OR (t.UPDATE_BY IN ('吴同', 'mdm_first_five') AND t.UPDATE_TIME = t.CREATE_TIME)
            THEN s.ENTERED_AT
        ELSE t.UPDATE_TIME
    END
WHERE t.DEL_FLAG = 0
  AND (t.CREATE_TIME IS NULL OR t.CREATE_TIME <> s.ENTERED_AT)
  AND (t.UPDATE_TIME IS NULL OR t.UPDATE_TIME >= s.ENTERED_AT
       OR (t.UPDATE_BY IN ('吴同', 'mdm_first_five') AND t.UPDATE_TIME = t.CREATE_TIME));

