/**
 * 根据对象组成员生成待提交结果和字段明细。
 *
 * @author chentangwen
 * @date 2026-09-22
 */
@Component
public class MergeResultFactory {
    @Resource
    private MergeRecordMapper mergeRecordMapper;
    @Resource
    private MergePendingMasterMapper mergePendingMasterMapper;
    @Resource
    private MergePendingMasterFieldMapper mergePendingMasterFieldMapper;
    @Resource
    private IMergeSourceTableService sourceTableService;

    /** 校验并锁定目标来源后生成结果、字段推荐及生存规则快照，参与调用方审核事务。 */
    @Transactional(rollbackFor = Exception.class)
    public MergePendingMasterDO create(Long groupId, Long modelId, Long modelVersionId, String processType,
                                        List<SourceSnapshot> snapshots, List<ModelColumnDO> columns,
                                        List<RuleSurvivorDO> survivorRules, Long operatorId, String operatorName) {
        MergePendingMasterDO existing = validateSources(groupId, modelId, snapshots);
        if (existing != null) {
            return existing;
        }
        Date now = new Date();
        Map<String, String> recommended = new LinkedHashMap<>();
        List<MergePendingMasterFieldDO> fields = new ArrayList<>();
        for (ModelColumnDO column : columns) {
            List<MergeValueInputBO> inputs = new ArrayList<>();
            for (SourceSnapshot snapshot : snapshots) {
                String value = snapshot.getValues().get(column.getCode());
                if (value == null) {
                    value = snapshot.getValues().get(String.valueOf(column.getId()));
                }
                MergeValueInputBO input = new MergeValueInputBO();
                input.setValue(value);
                input.setVersionId(snapshot.getVersionId());
                input.setSystemCode(snapshot.getSystemCode());
                input.setSystemName(snapshot.getSystemName());
                input.setTrust(snapshot.getTrustScore());
                input.setReceiveTime(snapshot.getReceiveTime() == null ? 0L : snapshot.getReceiveTime().getTime());
                inputs.add(input);
            }
            // 系统字段和自动编码在正式生效时生成，不采用来源值，也不产生人工冲突。
            boolean autoGenerated = ModelColumnCategoryEnum.SYSTEM.getValue().equalsIgnoreCase(column.getColumnCategory())
                || column.getEncodingVersionId() != null;
            MergeValueDecisionBO decision = autoGenerated ? new MergeValueDecisionBO()
                    : MergeValueDecider.decide(inputs, survivorRules, column.getCode(), String.valueOf(column.getId()));
            MergePendingMasterFieldDO field = new MergePendingMasterFieldDO();
            field.setModelColumnId(column.getId());
            field.setFieldPath(column.getCode());
            field.setRecommendedValue(decision.getValue());
            field.setFinalValue(decision.isConflict() ? null : decision.getValue());
            if (decision.isConflict()) {
                field.setValueSourceType(null);
            } else if (MergeCodes.PROCESS_SINGLE.equals(processType)) {
                field.setValueSourceType(MergeCodes.VALUE_SINGLE_DEFAULT);
            } else if (decision.getRuleId() != null) {
                field.setValueSourceType(MergeCodes.VALUE_SURVIVOR);
            } else {
                field.setValueSourceType(MergeCodes.VALUE_FALLBACK);
            }
            field.setSourceVersionId(decision.getVersionId());
            field.setSurvivorRuleId(decision.getRuleId());
            field.setConflictFlag(decision.isConflict() ? MergeCodes.YES : MergeCodes.NO);
            field.setResolvedFlag(decision.isConflict() ? MergeCodes.NO : MergeCodes.YES);
            field.setManualOverrideFlag(MergeCodes.NO);
            field.setValidFlag(MergeCodes.YES);
            field.setDelFlag(MergeCodes.NO);
            MergeAudit.fill(field, operatorId, operatorName);
            fields.add(field);
            recommended.put(column.getCode(), decision.getValue());
        }
        String recommendation = MergeJson.toJson(recommended);
        MergeRecordDO record = new MergeRecordDO();
        record.setObjectGroupId(groupId);
        record.setModelId(modelId);
        record.setProcessType(processType);
        record.setSurvivorRuleSnapshot(snapshotRules(survivorRules));
        record.setRecommendationData(recommendation);
        record.setStatus(MergeCodes.TASK_SUCCESS);
        record.setStartTime(now);
        record.setEndTime(now);
        record.setOperatorId(operatorId == null ? 0L : operatorId);
        record.setValidFlag(MergeCodes.YES);
        record.setDelFlag(MergeCodes.NO);
        MergeAudit.fill(record, operatorId, operatorName);
        mergeRecordMapper.insert(record);

        MergePendingMasterDO pending = new MergePendingMasterDO();
        pending.setModelId(modelId);
        pending.setModelVersionId(modelVersionId);
        pending.setObjectGroupId(groupId);
        pending.setMergeRecordId(record.getId());
        pending.setStatus(MergeCodes.PENDING_WAIT_CONFIRM);
        pending.setResultVersionNo(1);
        pending.setResultData(recommendation);
        pending.setQualityStatus(MergeCodes.QUALITY_NONE);
        pending.setValidFlag(MergeCodes.YES);
        pending.setDelFlag(MergeCodes.NO);
        MergeAudit.fill(pending, operatorId, operatorName);
        mergePendingMasterMapper.insert(pending);
        for (MergePendingMasterFieldDO field : fields) {
            field.setPendingId(pending.getId());
            mergePendingMasterFieldMapper.insert(field);
        }
        return pending;
    }

    /** 按来源编号取锁，检查有效性与已有结果归属；历史参考记录不独立占用结果。 */
    private MergePendingMasterDO validateSources(Long groupId, Long modelId, List<SourceSnapshot> snapshots) {
        TreeSet<Long> sourceIds = new TreeSet<>();
        if (snapshots != null) {
            for (SourceSnapshot snapshot : snapshots) {
                if (snapshot == null || snapshot.getSourceRecordId() == null || snapshot.getVersionId() == null) {
                    throw new ServiceException("来源快照不完整，不能生成待提交结果");
                }
                if (snapshot.isTarget() && !sourceIds.add(snapshot.getSourceRecordId())) {
                    throw new ServiceException("同一来源记录不能重复参与结果生成");
                }
            }
        }
        if (sourceIds.isEmpty()) {
            throw new ServiceException("历史比较数据不能单独生成待提交结果");
        }
        // 按来源 ID 顺序加锁，串行化同一来源的结果生成并避免反向加锁。
        List<MergeSourceRecordBO> sources = new ArrayList<>();
        for (Long sourceId : sourceIds) {
            MergeSourceRecordBO source = sourceTableService.lock(modelId, sourceId);
            if (source == null || !Objects.equals(modelId, source.getModelId())) {
                throw new ServiceException("来源记录不存在、已失效或不属于当前模型");
            }
            sources.add(source);
        }
        MergePendingMasterDO existing = mergePendingMasterMapper.selectByGroupForUpdate(groupId);
        if (existing != null) {
            return existing;
        }
        for (MergeSourceRecordBO source : sources) {
            if (!MergeCodes.GOVERNANCE_PENDING.equals(source.getGovernanceStatus())
                    && !MergeCodes.GOVERNANCE_PROCESSING.equals(source.getGovernanceStatus())) {
                throw new ServiceException("来源记录 " + source.getId() + " 已完成治理，不能再次作为待处理来源");
            }
        }
        // 撤回、取消、驳回仍保留原治理归属；只有显式失效后才允许重新处理。
        List<Long> occupied = mergePendingMasterMapper.selectOccupiedSourceIds(groupId, new ArrayList<Long>(sourceIds));
        if (!occupied.isEmpty()) {
            throw new ServiceException("来源记录 " + occupied.get(0) + " 已参与其他有效治理结果，不能重复生成");
        }
        return null;
    }

    /** 固定本次参与结果生成的生存规则配置，供后续追溯。 */
    private String snapshotRules(List<RuleSurvivorDO> rules) {
        List<Map<String, Object>> rows = new ArrayList<>();
        if (rules != null) {
            for (RuleSurvivorDO rule : rules) {
                Map<String, Object> row = new LinkedHashMap<>();
                row.put("id", rule.getId());
                row.put("ruleName", rule.getRuleName());
                row.put("ruleType", rule.getRuleType());
                row.put("modelFieldId", rule.getModelFieldId());
                row.put("ruleConfig", rule.getRuleConfig());
                rows.add(row);
            }
        }
        return MergeJson.toJson(rows);
    }
}
