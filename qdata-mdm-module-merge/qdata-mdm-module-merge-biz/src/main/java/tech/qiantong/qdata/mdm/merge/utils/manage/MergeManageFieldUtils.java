package tech.qiantong.qdata.mdm.merge.utils.manage;

import tech.qiantong.qdata.mdm.model.dal.dataobject.base.ModelColumnDO;
import tech.qiantong.qdata.mdm.model.enums.ModelColumnCategoryEnum;

/**
 * 合并管理中的字段生成与可编辑规则，展示、调整和质检使用同一判断。
 *
 * @author chentangwen
 */
public final class MergeManageFieldUtils {

    private MergeManageFieldUtils() {
    }

    /**
     * 系统字段和配置自动编码的字段由系统生成，不进行人工调整。
     */
    public static boolean autoGenerated(ModelColumnDO column) {
        return column != null && (ModelColumnCategoryEnum.SYSTEM.getValue().equalsIgnoreCase(column.getColumnCategory())
                || column.getEncodingVersionId() != null);
    }

    /**
     * 模型字段存在且不由系统生成时，允许调整取值。
     */
    public static boolean editable(ModelColumnDO column) {
        return column != null && !autoGenerated(column);
    }

    /** 整数字段按模型发布的 BIGINT 范围校验，空值由必填规则处理。 */
    public static String valueError(ModelColumnDO column, String value) {
        if (column == null || autoGenerated(column) || value == null || value.trim().isEmpty()) {
            return null;
        }
        String type = column.getDataType() == null ? "" : column.getDataType().trim().toUpperCase(java.util.Locale.ROOT);
        if (!java.util.Arrays.asList("INTEGER", "INT", "BIGINT", "SMALLINT", "TINYINT").contains(type)) {
            return null;
        }
        if (!value.matches("[+-]?[0-9]+")) {
            return "请输入有效整数";
        }
        try {
            Long.parseLong(value);
            return null;
        } catch (NumberFormatException ex) {
            return "整数超出允许范围";
        }
    }
}
